# OpenMap/Data/Changelog.lua from CHANGELOG.md: the latest versions' notes as plain text, for the
# addon's "What's new" window (Map/News.lua). Run it whenever CHANGELOG.md changes (lint.py checks
# the two agree), and before tagging a release (docs/releasing.md).
#
# usage: python -P tools/changelog/build.py [--check]
#   --check: write nothing; exit 1 if Data/Changelog.lua isn't what CHANGELOG.md makes
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "CHANGELOG.md")
OUT = os.path.join(ROOT, "OpenMap", "Data", "Changelog.lua")
VERSIONS = 6                    # the latest this many sections (an empty "Unreleased" doesn't count)


def plain(text):
    """markdown to plain text: links' words, no backticks or emphasis; no "|" (WoW's escape codes)"""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = text.replace("`", "").replace("|", "/")
    # (bold: a change's lead-in, in a deeper ink in the game; WoW's colour code, so after the "|"s)
    text = re.sub(r"\*\*(.+?)\*\*", r"|cff6e2c0a\1|r", text).replace("**", "")
    # (arrows the game's fonts don't have: they showed as boxes)
    text = text.replace("→", ">").replace("▶", ">").replace("◀", "<")
    return re.sub(r"\s+", " ", text).strip()


def sections(md):
    out, cur, item = [], None, None
    for line in md.splitlines():
        m = re.match(r"^## (.+?)\s*$", line)
        if m:
            head = m.group(1)
            v = re.match(r"^(\S+)\s*\((\d{4}-\d{2}-\d{2})\)$", head)
            cur = {"version": v.group(1) if v else head, "date": v.group(2) if v else "", "items": [], "heads": {}}
            out.append(cur)
            item = None
            continue
        if cur is None:
            continue
        g = re.match(r"^### (.+?)\s*$", line)      # (a version's kinds of change: New, Improved, Fixed)
        if g:
            cur["heads"][len(cur["items"]) + 1] = plain(g.group(1))
            item = None
            continue
        if line.startswith("- "):
            item = [line[2:]]
            cur["items"].append(item)
        elif item is not None and line.startswith("  ") and line.strip():
            item.append(line.strip())
        elif not line.strip():
            item = None
    for s in out:
        s["items"] = [plain(" ".join(i)) for i in s["items"]]
    return [s for s in out if s["items"]][:VERSIONS]


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build():
    secs = sections(open(SRC, encoding="utf-8").read())
    lines = [
        "-- The latest versions' notes, for the \"What's new\" window (Map/News.lua), from CHANGELOG.md.",
        "-- Generated by tools/changelog/build.py; regenerate rather than edit.",
        "",
        "local _, ns = ...",
        "",
        "ns.MapChangelog = {",
    ]
    for s in secs:
        # (heads: a heading before the item at that place)
        heads = "".join("[%d] = %s, " % (k, lua_string(v)) for k, v in sorted(s["heads"].items()))
        lines.append("\t{ version = %s, date = %s, heads = { %s}, items = {" % (lua_string(s["version"]), lua_string(s["date"]), heads))
        for it in s["items"]:
            lines.append("\t\t%s," % lua_string(it))
        lines.append("\t} },")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("Data/Changelog.lua is out of date with CHANGELOG.md: run python -P tools/changelog/build.py")
            sys.exit(1)
        print("changelog: up to date")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", OUT)
